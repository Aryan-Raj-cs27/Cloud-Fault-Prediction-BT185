"""Optuna hyperparameter search on the VALIDATION split (CLAUDE.md §7.4).

Budget (documented in docs/EXPERIMENTS.md): xgboost 40 trials, random_forest 12 trials,
objective = validation PR-AUC on the primary observation window. Writes
``configs/model/tuned.yaml``. The test split is never loaded.

Usage:
    python scripts/tune.py [--trials-xgb 40] [--trials-rf 12]
"""

from __future__ import annotations

import argparse
from typing import Any

import optuna
from omegaconf import OmegaConf
from sklearn.metrics import average_precision_score

from faultaware.features.store import get_features, load_bundle
from faultaware.models.base import create_model
from faultaware.training.runner import model_params
from faultaware.utils.config import CONFIG_DIR, load_config
from faultaware.utils.logging import get_logger

log = get_logger("tune")


def main() -> None:
    """CLI entry point."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--trials-xgb", type=int, default=40)
    parser.add_argument("--trials-rf", type=int, default=12)
    args, overrides = parser.parse_known_args()
    cfg = load_config(overrides)
    bundle = load_bundle(cfg)
    window = cfg.data.default_observation
    train = get_features(cfg, bundle, "train", window)
    val = get_features(cfg, bundle, "val", window)

    def objective_for(name: str, space: Any) -> Any:
        def objective(trial: optuna.Trial) -> float:
            params = {**model_params(name), **space(trial)}
            model = create_model(name, params, seed=cfg.seed)
            model.fit(train, train.y, val, val.y)
            return float(average_precision_score(val.y, model.predict_proba(val)))

        return objective

    def xgb_space(t: optuna.Trial) -> dict[str, Any]:
        return {
            "max_depth": t.suggest_int("max_depth", 3, 10),
            "learning_rate": t.suggest_float("learning_rate", 0.01, 0.3, log=True),
            "n_estimators": t.suggest_int("n_estimators", 100, 1000, step=100),
            "subsample": t.suggest_float("subsample", 0.6, 1.0),
            "colsample_bytree": t.suggest_float("colsample_bytree", 0.5, 1.0),
            "min_child_weight": t.suggest_float("min_child_weight", 0.5, 20, log=True),
            "reg_lambda": t.suggest_float("reg_lambda", 1e-3, 10, log=True),
        }

    def rf_space(t: optuna.Trial) -> dict[str, Any]:
        return {
            "n_estimators": t.suggest_int("n_estimators", 100, 500, step=100),
            "max_depth": t.suggest_categorical("max_depth", [8, 16, 24, None]),
            "min_samples_leaf": t.suggest_int("min_samples_leaf", 1, 20, log=True),
            "max_features": t.suggest_categorical("max_features", ["sqrt", 0.5]),
        }

    tuned: dict[str, dict[str, Any]] = {}
    for name, space, n_trials in (
        ("xgboost", xgb_space, args.trials_xgb),
        ("random_forest", rf_space, args.trials_rf),
    ):
        study = optuna.create_study(
            direction="maximize", sampler=optuna.samplers.TPESampler(seed=cfg.seed)
        )
        study.optimize(objective_for(name, space), n_trials=n_trials)
        log.info("%s best val PR-AUC %.4f with %s", name, study.best_value, study.best_params)
        tuned[name] = {
            **study.best_params,
            "_val_pr_auc": round(study.best_value, 5),
            "_trials": n_trials,
        }
    out = CONFIG_DIR / "model" / "tuned.yaml"
    out.write_text(
        "# Generated by scripts/tune.py — do not edit by hand.\n"
        + OmegaConf.to_yaml(OmegaConf.create(tuned)),
        encoding="utf-8",
    )
    log.info("wrote %s", out)


if __name__ == "__main__":
    main()
